
-- E-commerce SQL Reports
-- PostgreSQL | Java Mentorship - Session 3
-- Reporting assumptions:
-- All recorded orders count toward sales.
-- The selected reporting month is October 2026.

-- REPORT 1: Daily Revenue
SELECT
    ORDER_DATE,
    SUM(TOTAL_AMOUNT) AS DAILY_REVENUE
FROM ORDERS
GROUP BY ORDER_DATE
ORDER BY ORDER_DATE ASC;

-- REPORT 2: Top-Selling Products in October 2026
SELECT
    P.PRODUCT_NAME,
    SUM(OD.QUANTITY) AS TOTAL_QUANTITY
FROM ORDER_DETAILS OD
JOIN PRODUCT P
    ON OD.PRODUCT_ID = P.PRODUCT_ID
JOIN ORDERS O
    ON OD.ORDER_ID = O.ORDER_ID
WHERE O.ORDER_DATE >= '2026-10-01'
  AND O.ORDER_DATE < '2026-11-01'
GROUP BY P.PRODUCT_ID, P.PRODUCT_NAME
ORDER BY TOTAL_QUANTITY DESC, P.PRODUCT_NAME ASC;

-- REPORT 3: Customers Spending More Than $500 in October 2026
SELECT
    C.CUSTOMER_NAME,
    SUM(O.TOTAL_AMOUNT) AS TOTAL_SPENDING
FROM CUSTOMER C
JOIN ORDERS O
    ON O.CUSTOMER_ID = C.CUSTOMER_ID
WHERE O.ORDER_DATE >= '2026-10-01'
  AND O.ORDER_DATE < '2026-11-01'
GROUP BY C.CUSTOMER_ID, C.CUSTOMER_NAME
HAVING SUM(O.TOTAL_AMOUNT) > 500
ORDER BY TOTAL_SPENDING DESC;
  
